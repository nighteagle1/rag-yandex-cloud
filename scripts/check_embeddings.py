"""Проверка модели эмбеддингов на 5 русских парах «вопрос — релевантный абзац».

Модель проходит, если для каждого вопроса самый похожий абзац — свой,
и средний отрыв своего абзаца от лучшего чужого заметен.
    python scripts/check_embeddings.py [model ...]
"""
import sys

import numpy as np

import common

PAIRS = [
    ("Сколько времени может работать прерываемая ВМ до принудительной остановки?",
     "Прерываемые виртуальные машины — это виртуальные машины, которые могут быть принудительно остановлены в любой момент. "
     "Это может произойти, если с момента запуска виртуальной машины прошло 24 часа."),
    ("Можно ли к одной виртуалке привязать два сервисных аккаунта?",
     "К виртуальной машине можно привязать только один сервисный аккаунт."),
    ("Какого размера должен быть нереплицируемый диск?",
     "Вы можете создать отдельный нереплицируемый диск, либо добавить его в группу размещения дисков. Размер диска должен быть кратен 93 ГБ."),
    ("Клиенту не пришёл счёт на почту, куда его отправляют?",
     "Счет высылается только на адрес электронной почты пользователя, который создал платежный аккаунт. "
     "Изменить адрес нельзя, но можно настроить пересылку писем на другой адрес."),
    ("Как открыть публичный доступ к бакету на чтение объектов?",
     "По умолчанию бакеты создаются с ограниченным доступом. Вы можете открыть публичный доступ на чтение объектов в бакете, "
     "к списку объектов в бакете и на чтение настроек."),
]


def check(model: str) -> bool:
    common.EMBED_MODEL = model
    q = np.array(common.embed([p[0] for p in PAIRS]))
    d = np.array(common.embed([p[1] for p in PAIRS]))
    q /= np.linalg.norm(q, axis=1, keepdims=True)
    d /= np.linalg.norm(d, axis=1, keepdims=True)
    sim = q @ d.T
    diag = np.diag(sim)
    off = np.where(np.eye(len(PAIRS), dtype=bool), -1, sim).max(axis=1)
    ok = bool((diag > off).all())
    print(f"\n{model}  dim={q.shape[1]}")
    print(np.array2string(sim, precision=3))
    print(f"своя пара: {diag.mean():.3f}, лучшая чужая: {off.mean():.3f}, отрыв: {(diag - off).mean():.3f}, "
          f"все пары на первом месте: {ok}")
    return ok


if __name__ == "__main__":
    models = sys.argv[1:] or [common.EMBED_MODEL]
    results = {m: check(m) for m in models}
    sys.exit(0 if all(results.values()) else 1)
